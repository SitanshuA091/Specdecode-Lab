
import argparse
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

MODEL_ID = "Qwen/Qwen2.5-1.5B-Instruct"

device = "cuda" if torch.cuda.is_available() else "cpu"
dtype = torch.float16 if device == "cuda" else torch.float32

tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)

model = AutoModelForCausalLM.from_pretrained(
    MODEL_ID,
    torch_dtype=dtype,
).to(device)

model.eval()


@torch.inference_mode()
def verify_draft(prompt, draft_token_ids):

    messages = [{"role": "user", "content": prompt}]

    # Tokenize the conditioning prefix.
    inputs = tokenizer.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=True,
        return_tensors="pt",
        return_dict=True,
    ).to(device)

    input_ids = inputs["input_ids"]
    attention_mask = inputs["attention_mask"]

    # Append draft tokens to the conditioning prefix.
    candidate_ids = torch.tensor(
        [draft_token_ids],
        dtype=torch.long,
        device=device,
    )

    combined_ids = torch.cat(
        [input_ids, candidate_ids],
        dim=-1,
    )

    combined_mask = torch.ones_like(combined_ids)

    # Target processes the prefix and all draft tokens in one pass.
    outputs = model(
        input_ids=combined_ids,
        attention_mask=combined_mask,
        use_cache=True,
    )

    # Logits at prefix position predict draft token 1.
    # Subsequent positions predict the subsequent draft tokens.
    target_predictions = outputs.logits.argmax(dim=-1)

    prefix_length = input_ids.shape[-1]
    draft_length = candidate_ids.shape[-1]

    predictions = target_predictions[
        :, prefix_length - 1 : prefix_length + draft_length
    ]

    accepted_tokens = []
    corrected_token = None

    for i in range(draft_length):

        proposed = candidate_ids[0, i].item()
        predicted = predictions[0, i].item()

        if proposed == predicted:
            accepted_tokens.append(proposed)
        else:
            corrected_token = predicted
            break

    all_accepted = len(accepted_tokens) == draft_length

    # If every draft token is accepted, use the bonus prediction.
    if all_accepted:
        corrected_token = predictions[0, -1].item()

    accepted_ids = torch.tensor(
        accepted_tokens,
        dtype=torch.long,
        device=device,
    )

    corrected_ids = (
        torch.tensor([corrected_token], dtype=torch.long, device=device)
        if corrected_token is not None
        else None
    )

    return accepted_ids, corrected_ids, all_accepted


if __name__ == "__main__":

    parser = argparse.ArgumentParser(
        description="Greedy verification of speculative draft tokens"
    )

    parser.add_argument(
        "--prompt",
        type=str,
        required=True,
        help="Original input prompt",
    )

    parser.add_argument(
        "--draft-tokens",
        type=int,
        nargs="+",
        required=True,
        help="Draft token IDs generated by the draft model",
    )

    args = parser.parse_args()

    accepted, correction, all_accepted = verify_draft(
        args.prompt,
        args.draft_tokens,
    )

    print("\nAccepted draft tokens:")
    print(accepted.tolist())

    print("\nAccepted text:")
    print(tokenizer.decode(accepted, skip_special_tokens=True))

    if correction is not None:
        print("\nCorrection / bonus token:")
        print(correction.tolist())
        print(tokenizer.decode(correction, skip_special_tokens=True))

    print("\nAll draft tokens accepted:", all_accepted)


